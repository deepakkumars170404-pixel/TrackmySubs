async function seed() {
  console.log("Seeding Supabase subscriptions...");
  await supabase.from("subscriptions").delete().neq("id", "0000");

  const { data, error } = await supabase.from("subscriptions").insert(ALL_HOUSEHOLD_SUBSCRIPTIONS);
  if (error) {
    console.error("Supabase insert error:", error);
  } else {
    console.log(`Successfully seeded ${ALL_HOUSEHOLD_SUBSCRIPTIONS.length} subscriptions!`);
    const total = ALL_HOUSEHOLD_SUBSCRIPTIONS.reduce((s, x) => s + x.monthly_cost, 0);
    console.log(`Verified total monthly spend: ₹${total}`);
  }
}

seed();
